//! Explicit, idempotent and reversible shell integration setup.
//!
//! * Bash/Zsh: a generated script under `$XDG_DATA_HOME/tabtrail/shell/` and a
//!   clearly marked block in `~/.bashrc` / `${ZDOTDIR:-~}/.zshrc` that sources
//!   it if present. Re-running replaces the block in place; uninstall
//!   removes exactly the block. Nothing else in the file is touched.
//! * Fish: a single owned file `~/.config/fish/conf.d/tabtrail.fish`.
//! * Symlinked rc files (dotfile managers) are edited at their target.
//! * Malformed markers are reported, never guessed at.

use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::app::Shell;
use crate::fsutil::write_atomic;

pub const BEGIN: &str = "# >>> tabtrail initialize >>>";
pub const END: &str = "# <<< tabtrail initialize <<<";
const FISH_HEADER: &str = "# Generated by `tabtrail install --shell fish`; removed by `tabtrail uninstall`.";

const BASH_SCRIPT: &str = include_str!("../shell/tabtrail.bash");
const ZSH_SCRIPT: &str = include_str!("../shell/tabtrail.zsh");
const FISH_SCRIPT: &str = include_str!("../shell/tabtrail.fish");

/// Quotes a path as a single-quoted POSIX shell word.
pub fn sh_single_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// Quotes a path as a single-quoted Fish word.
pub fn fish_single_quote(s: &str) -> String {
    format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"))
}

/// The integration script for `shell`, with the helper path embedded.
pub fn init_script(shell: Shell, bin: &str) -> String {
    match shell {
        Shell::Bash => format!("__tabtrail_bin={}\n{BASH_SCRIPT}", sh_single_quote(bin)),
        Shell::Zsh => format!("typeset -g __tabtrail_bin={}\n{ZSH_SCRIPT}", sh_single_quote(bin)),
        Shell::Fish => format!("set -g __tabtrail_bin {}\n{FISH_SCRIPT}", fish_single_quote(bin)),
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Paths {
    pub home: PathBuf,
    pub data: PathBuf,
    pub config_home: PathBuf,
    pub zdotdir: Option<PathBuf>,
}

impl Paths {
    pub fn from_env(data: &Path) -> Option<Paths> {
        let home = PathBuf::from(std::env::var_os("HOME").filter(|h| !h.is_empty())?);
        let config_home = std::env::var_os("XDG_CONFIG_HOME")
            .map(PathBuf::from)
            .filter(|p| p.is_absolute())
            .unwrap_or_else(|| home.join(".config"));
        let zdotdir = std::env::var_os("ZDOTDIR")
            .map(PathBuf::from)
            .filter(|p| p.is_absolute());
        Some(Paths {
            home,
            data: data.to_path_buf(),
            config_home,
            zdotdir,
        })
    }

    pub fn rc_file(&self, shell: Shell) -> PathBuf {
        match shell {
            Shell::Bash => self.home.join(".bashrc"),
            Shell::Zsh => self.zdotdir.clone().unwrap_or_else(|| self.home.clone()).join(".zshrc"),
            Shell::Fish => self.config_home.join("fish/conf.d/tabtrail.fish"),
        }
    }

    pub fn script_file(&self, shell: Shell) -> PathBuf {
        self.data.join("shell").join(format!("tabtrail.{}", shell.name()))
    }
}

#[derive(Debug)]
pub enum InstallError {
    Io(PathBuf, io::Error),
    MalformedMarkers(PathBuf),
    NotOurs(PathBuf),
    DanglingSymlink(PathBuf),
}

impl std::fmt::Display for InstallError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            InstallError::Io(p, e) => write!(f, "{}: {e}; nothing was changed", p.display()),
            InstallError::MalformedMarkers(p) => write!(
                f,
                "{}: Tabtrail marker lines are unbalanced, duplicated or embedded in other text; \
                 nothing was changed. Fix the lines `{BEGIN}` / `{END}` manually.",
                p.display()
            ),
            InstallError::NotOurs(p) => write!(
                f,
                "{}: exists but was not created by Tabtrail; left unchanged",
                p.display()
            ),
            InstallError::DanglingSymlink(p) => {
                write!(
                    f,
                    "{}: is a symlink whose target does not exist; left unchanged",
                    p.display()
                )
            }
        }
    }
}

/// The rc file's marker lines are unbalanced, duplicated, out of order or
/// embedded in other text.
#[derive(Debug, PartialEq, Eq)]
pub struct AmbiguousMarkers;

/// Inside a block: records that the installer had to terminate the user's
/// last line with a newline, so uninstall can restore the exact bytes.
const NEWLINE_NOTE: &str = "# tabtrail: a final newline was added before this block";

#[derive(Debug, PartialEq, Eq)]
struct Block {
    /// Byte range of the block's lines, including the END line's newline.
    start: usize,
    end: usize,
    added_newline: bool,
}

/// Splits into (start offset, line without the trailing newline).
fn lines(data: &[u8]) -> Vec<(usize, &[u8])> {
    let mut out = Vec::new();
    let mut start = 0;
    for (i, b) in data.iter().enumerate() {
        if *b == b'\n' {
            out.push((start, &data[start..i]));
            start = i + 1;
        }
    }
    if start < data.len() {
        out.push((start, &data[start..]));
    }
    out
}

fn contains(hay: &[u8], needle: &[u8]) -> bool {
    hay.windows(needle.len()).any(|w| w == needle)
}

/// Locates the block delimited by lines that consist exactly of the
/// markers. Ok(None): no markers at all. Err: anything ambiguous (marker
/// text embedded in another line, duplicates, wrong order, missing end).
fn find_block(data: &[u8]) -> Result<Option<Block>, AmbiguousMarkers> {
    let (begin, end) = (BEGIN.as_bytes(), END.as_bytes());
    let mut b = None;
    let mut e = None;
    let mut note = false;
    for (off, line) in lines(data) {
        let line_trim = line.strip_suffix(b"\r").unwrap_or(line);
        if line_trim == begin {
            if b.is_some() {
                return Err(AmbiguousMarkers);
            }
            b = Some(off);
        } else if line_trim == end {
            if e.is_some() || b.is_none() {
                return Err(AmbiguousMarkers);
            }
            let mut stop = off + line.len();
            if data.get(stop) == Some(&b'\n') {
                stop += 1;
            }
            e = Some(stop);
        } else if contains(line, begin) || contains(line, end) {
            return Err(AmbiguousMarkers);
        } else if b.is_some() && e.is_none() && line_trim == NEWLINE_NOTE.as_bytes() {
            note = true;
        }
    }
    match (b, e) {
        (None, None) => Ok(None),
        (Some(start), Some(end)) => Ok(Some(Block {
            start,
            end,
            added_newline: note,
        })),
        _ => Err(AmbiguousMarkers),
    }
}

pub fn rc_block(script: &Path, added_newline: bool) -> String {
    let q = sh_single_quote(&script.to_string_lossy());
    let mut b = String::new();
    let _ = writeln!(b, "{BEGIN}");
    let _ = writeln!(b, "# Added by `tabtrail install`; remove with `tabtrail uninstall`.");
    if added_newline {
        let _ = writeln!(b, "{NEWLINE_NOTE}");
    }
    let _ = writeln!(b, "if [ -r {q} ]; then . {q}; fi");
    let _ = writeln!(b, "{END}");
    b
}

/// Returns the new rc bytes with the block inserted (appended) or replaced
/// in place. All other bytes are preserved exactly.
pub fn with_block(data: &[u8], script: &Path) -> Result<Vec<u8>, AmbiguousMarkers> {
    match find_block(data)? {
        Some(blk) => {
            let mut out = data[..blk.start].to_vec();
            out.extend_from_slice(rc_block(script, blk.added_newline).as_bytes());
            out.extend_from_slice(&data[blk.end..]);
            Ok(out)
        }
        None => {
            let mut out = data.to_vec();
            let add_newline = !out.is_empty() && !out.ends_with(b"\n");
            if add_newline {
                out.push(b'\n');
            }
            out.extend_from_slice(rc_block(script, add_newline).as_bytes());
            Ok(out)
        }
    }
}

/// Returns the rc bytes without the block (None if there was no block).
pub fn without_block(data: &[u8]) -> Result<Option<Vec<u8>>, AmbiguousMarkers> {
    let Some(blk) = find_block(data)? else { return Ok(None) };
    let mut head = &data[..blk.start];
    if blk.added_newline && head.ends_with(b"\n") {
        head = &head[..head.len() - 1];
    }
    let mut out = head.to_vec();
    out.extend_from_slice(&data[blk.end..]);
    Ok(Some(out))
}

/// Resolves a symlinked rc file to its target so the link is preserved.
/// A dangling link is an error rather than being replaced by a file.
fn edit_target(path: &Path) -> Result<PathBuf, InstallError> {
    match fs::symlink_metadata(path) {
        Ok(m) if m.file_type().is_symlink() => {
            fs::canonicalize(path).map_err(|_| InstallError::DanglingSymlink(path.to_path_buf()))
        }
        _ => Ok(path.to_path_buf()),
    }
}

/// Reads a file; Ok(None) only when it does not exist. Any other failure
/// (permissions, I/O, ...) is an error so nothing is overwritten blindly.
fn read_existing(path: &Path) -> Result<Option<Vec<u8>>, InstallError> {
    // Bounded and non-blocking: a FIFO or huge file in place of an rc file
    // is an error, never a hang or an overwrite.
    crate::fsutil::read_regular(path, 16 * 1024 * 1024).map_err(|e| InstallError::Io(path.to_path_buf(), e))
}

fn write_preserving_mode(path: &Path, data: &[u8]) -> io::Result<()> {
    let mode = fs::metadata(path).ok().map(|m| m.permissions());
    write_atomic(path, data)?;
    if let Some(perm) = mode {
        fs::set_permissions(path, perm)?;
    }
    Ok(())
}

#[derive(Debug, Default, PartialEq, Eq)]
pub struct Changes {
    pub written: Vec<PathBuf>,
    pub removed: Vec<PathBuf>,
    pub unchanged: Vec<PathBuf>,
}

pub fn install(paths: &Paths, shell: Shell, bin: &str, dry_run: bool) -> Result<Changes, InstallError> {
    let mut changes = Changes::default();
    let script = init_script(shell, bin);
    let io = |p: &Path| {
        let p = p.to_path_buf();
        move |e| InstallError::Io(p, e)
    };
    match shell {
        Shell::Fish => {
            let file = edit_target(&paths.rc_file(shell))?;
            let content = format!("{FISH_HEADER}\n{script}");
            match read_existing(&file)? {
                Some(existing) if existing == content.as_bytes() => changes.unchanged.push(file),
                Some(existing) if !existing.starts_with(FISH_HEADER.as_bytes()) => {
                    return Err(InstallError::NotOurs(file));
                }
                _ => {
                    if !dry_run {
                        write_atomic(&file, content.as_bytes()).map_err(io(&file))?;
                    }
                    changes.written.push(file);
                }
            }
        }
        Shell::Bash | Shell::Zsh => {
            // Validate the rc file before writing anything.
            let rc = edit_target(&paths.rc_file(shell))?;
            let text = read_existing(&rc)?.unwrap_or_default();
            let script_file = paths.script_file(shell);
            let new = with_block(&text, &script_file).map_err(|_| InstallError::MalformedMarkers(rc.clone()))?;
            if read_existing(&script_file)?.as_deref() == Some(script.as_bytes()) {
                changes.unchanged.push(script_file.clone());
            } else {
                if !dry_run {
                    write_atomic(&script_file, script.as_bytes()).map_err(io(&script_file))?;
                }
                changes.written.push(script_file.clone());
            }
            if new == text {
                changes.unchanged.push(rc);
            } else {
                if !dry_run {
                    write_preserving_mode(&rc, &new).map_err(io(&rc))?;
                }
                changes.written.push(rc);
            }
        }
    }
    Ok(changes)
}

pub fn uninstall(paths: &Paths, shell: Shell, dry_run: bool) -> Result<Changes, InstallError> {
    let mut changes = Changes::default();
    let io = |p: &Path| {
        let p = p.to_path_buf();
        move |e| InstallError::Io(p, e)
    };
    match shell {
        Shell::Fish => {
            let file = edit_target(&paths.rc_file(shell))?;
            match read_existing(&file)? {
                Some(t) if t.starts_with(FISH_HEADER.as_bytes()) => {
                    if !dry_run {
                        fs::remove_file(&file).map_err(io(&file))?;
                    }
                    changes.removed.push(file);
                }
                Some(_) => return Err(InstallError::NotOurs(file)),
                None => changes.unchanged.push(file),
            }
        }
        Shell::Bash | Shell::Zsh => {
            let rc = edit_target(&paths.rc_file(shell))?;
            if let Some(text) = read_existing(&rc)? {
                match without_block(&text) {
                    Ok(Some(new)) => {
                        if !dry_run {
                            write_preserving_mode(&rc, &new).map_err(io(&rc))?;
                        }
                        changes.written.push(rc);
                    }
                    Ok(None) => changes.unchanged.push(rc),
                    Err(AmbiguousMarkers) => return Err(InstallError::MalformedMarkers(rc)),
                }
            }
            let script = paths.script_file(shell);
            if script.exists() {
                if !dry_run {
                    fs::remove_file(&script).map_err(io(&script))?;
                }
                changes.removed.push(script);
            }
        }
    }
    Ok(changes)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::testutil::TempDir;

    fn paths(t: &TempDir) -> Paths {
        Paths {
            home: t.path().join("home"),
            data: t.path().join("home/.local/share/tabtrail"),
            config_home: t.path().join("home/.config"),
            zdotdir: None,
        }
    }

    #[test]
    fn quoting_is_safe_for_hostile_paths() {
        assert_eq!(sh_single_quote("/a b/it's"), r"'/a b/it'\''s'");
        assert_eq!(fish_single_quote(r"/a\b/it's"), r"'/a\\b/it\'s'");
    }

    #[test]
    fn bash_install_is_idempotent_and_reversible() {
        let t = TempDir::new("install");
        let p = paths(&t);
        fs::create_dir_all(&p.home).unwrap();
        let rc = p.home.join(".bashrc");
        let original = "# user stuff\nalias ll='ls -l'\nexport X=1";
        fs::write(&rc, original).unwrap();
        let c1 = install(&p, Shell::Bash, "/opt/tt/bin/tabtrail", false).unwrap();
        assert_eq!(c1.written.len(), 2);
        let after1 = fs::read_to_string(&rc).unwrap();
        assert!(after1.starts_with(original));
        assert_eq!(after1.matches(BEGIN).count(), 1);
        let c2 = install(&p, Shell::Bash, "/opt/tt/bin/tabtrail", false).unwrap();
        assert!(c2.written.is_empty(), "second install changes nothing: {c2:?}");
        assert_eq!(fs::read_to_string(&rc).unwrap(), after1);
        // user edits after the block survive reinstall with a new binary path
        fs::write(&rc, format!("{after1}export AFTER=1\n")).unwrap();
        install(&p, Shell::Bash, "/new/tabtrail", false).unwrap();
        let after3 = fs::read_to_string(&rc).unwrap();
        assert!(after3.ends_with("export AFTER=1\n"));
        assert!(
            fs::read_to_string(p.script_file(Shell::Bash))
                .unwrap()
                .starts_with("__tabtrail_bin='/new/tabtrail'")
        );
        uninstall(&p, Shell::Bash, false).unwrap();
        let restored = fs::read_to_string(&rc).unwrap();
        // byte-exact: the newline the installer added is removed again
        assert_eq!(restored, format!("{original}export AFTER=1\n"));
        assert!(!p.script_file(Shell::Bash).exists());
        // uninstall again is a no-op
        let c = uninstall(&p, Shell::Bash, false).unwrap();
        assert!(c.written.is_empty() && c.removed.is_empty());
    }

    #[test]
    fn missing_rc_is_created_and_symlinks_are_preserved() {
        let t = TempDir::new("install-link");
        let p = paths(&t);
        fs::create_dir_all(&p.home).unwrap();
        install(&p, Shell::Zsh, "/b/tabtrail", false).unwrap();
        assert!(fs::read_to_string(p.home.join(".zshrc")).unwrap().contains(BEGIN));
        let dotfiles = t.path().join("dotfiles");
        fs::create_dir_all(&dotfiles).unwrap();
        fs::write(dotfiles.join("bashrc"), "echo hi\n").unwrap();
        std::os::unix::fs::symlink(dotfiles.join("bashrc"), p.home.join(".bashrc")).unwrap();
        install(&p, Shell::Bash, "/b/tabtrail", false).unwrap();
        assert!(
            fs::symlink_metadata(p.home.join(".bashrc"))
                .unwrap()
                .file_type()
                .is_symlink()
        );
        assert!(fs::read_to_string(dotfiles.join("bashrc")).unwrap().contains(BEGIN));
    }

    #[test]
    fn malformed_markers_are_not_touched() {
        let t = TempDir::new("install-bad");
        let p = paths(&t);
        fs::create_dir_all(&p.home).unwrap();
        let rc = p.home.join(".bashrc");
        let bad = format!("{BEGIN}\nhalf a block\n");
        fs::write(&rc, &bad).unwrap();
        assert!(matches!(
            install(&p, Shell::Bash, "/b", false),
            Err(InstallError::MalformedMarkers(_))
        ));
        assert!(matches!(
            uninstall(&p, Shell::Bash, false),
            Err(InstallError::MalformedMarkers(_))
        ));
        assert_eq!(fs::read_to_string(&rc).unwrap(), bad);
    }

    #[test]
    fn fish_owned_file_and_foreign_file_protection() {
        let t = TempDir::new("install-fish");
        let p = paths(&t);
        let f = p.rc_file(Shell::Fish);
        install(&p, Shell::Fish, "/b/tabtrail", false).unwrap();
        assert!(fs::read_to_string(&f).unwrap().contains("complete -p '*'"));
        uninstall(&p, Shell::Fish, false).unwrap();
        assert!(!f.exists());
        fs::write(&f, "# someone else's file\n").unwrap();
        assert!(matches!(
            install(&p, Shell::Fish, "/b", false),
            Err(InstallError::NotOurs(_))
        ));
        assert!(matches!(
            uninstall(&p, Shell::Fish, false),
            Err(InstallError::NotOurs(_))
        ));
        assert_eq!(fs::read_to_string(&f).unwrap(), "# someone else's file\n");
    }

    #[test]
    fn exact_restore_with_and_without_final_newline() {
        let t = TempDir::new("install-exact");
        let p = paths(&t);
        fs::create_dir_all(&p.home).unwrap();
        let rc = p.home.join(".bashrc");
        for original in [
            &b""[..],
            b"a\n",
            b"no-final-newline",
            b"x\n\n\n",
            b"\xff\xfe binary \x00 bytes\n",
        ] {
            fs::write(&rc, original).unwrap();
            install(&p, Shell::Bash, "/b/tabtrail", false).unwrap();
            uninstall(&p, Shell::Bash, false).unwrap();
            assert_eq!(
                fs::read(&rc).unwrap(),
                original,
                "{:?}",
                String::from_utf8_lossy(original)
            );
        }
    }

    #[test]
    fn embedded_marker_text_is_rejected_not_deleted() {
        let t = TempDir::new("install-embedded");
        let p = paths(&t);
        fs::create_dir_all(&p.home).unwrap();
        let rc = p.home.join(".bashrc");
        let tricky = format!("echo \"{BEGIN}\"\nexport KEEP=1\necho \"{END}\"\n");
        fs::write(&rc, &tricky).unwrap();
        assert!(matches!(
            uninstall(&p, Shell::Bash, false),
            Err(InstallError::MalformedMarkers(_))
        ));
        assert!(matches!(
            install(&p, Shell::Bash, "/b", false),
            Err(InstallError::MalformedMarkers(_))
        ));
        assert_eq!(fs::read_to_string(&rc).unwrap(), tricky);
        assert!(
            !p.script_file(Shell::Bash).exists(),
            "nothing written when the rc file is ambiguous"
        );
        // duplicated or reversed markers are rejected too
        for bad in [
            format!("{END}\n{BEGIN}\n"),
            format!("{BEGIN}\n{BEGIN}\n{END}\n"),
            format!("{BEGIN}\n{END}\n{END}\n"),
        ] {
            fs::write(&rc, &bad).unwrap();
            assert!(uninstall(&p, Shell::Bash, false).is_err(), "{bad}");
            assert_eq!(fs::read_to_string(&rc).unwrap(), bad);
        }
    }

    #[test]
    fn unreadable_or_non_utf8_fish_file_is_never_overwritten() {
        let t = TempDir::new("install-fish-bytes");
        let p = paths(&t);
        let f = p.rc_file(Shell::Fish);
        fs::create_dir_all(f.parent().unwrap()).unwrap();
        let foreign = b"# mine\n\xff\xfe\n";
        fs::write(&f, foreign).unwrap();
        assert!(matches!(
            install(&p, Shell::Fish, "/b", false),
            Err(InstallError::NotOurs(_))
        ));
        assert!(matches!(
            uninstall(&p, Shell::Fish, false),
            Err(InstallError::NotOurs(_))
        ));
        assert_eq!(fs::read(&f).unwrap(), foreign);
        // a directory in place of the file: read error, fail closed
        fs::remove_file(&f).unwrap();
        fs::create_dir(&f).unwrap();
        assert!(matches!(
            install(&p, Shell::Fish, "/b", false),
            Err(InstallError::Io(..))
        ));
        assert!(f.is_dir());
    }

    #[test]
    fn dangling_rc_symlink_is_not_replaced() {
        let t = TempDir::new("install-dangling");
        let p = paths(&t);
        fs::create_dir_all(&p.home).unwrap();
        let rc = p.home.join(".bashrc");
        std::os::unix::fs::symlink(t.path().join("missing-target"), &rc).unwrap();
        assert!(matches!(
            install(&p, Shell::Bash, "/b", false),
            Err(InstallError::DanglingSymlink(_))
        ));
        assert!(fs::symlink_metadata(&rc).unwrap().file_type().is_symlink());
        assert!(!p.script_file(Shell::Bash).exists());
        assert!(matches!(
            uninstall(&p, Shell::Bash, false),
            Err(InstallError::DanglingSymlink(_))
        ));
    }

    #[test]
    fn dry_run_writes_nothing() {
        let t = TempDir::new("install-dry");
        let p = paths(&t);
        fs::create_dir_all(&p.home).unwrap();
        let c = install(&p, Shell::Bash, "/b", true).unwrap();
        assert_eq!(c.written.len(), 2);
        assert!(!p.home.join(".bashrc").exists());
        assert!(!p.script_file(Shell::Bash).exists());
    }
}
